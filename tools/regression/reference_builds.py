"""Rebuild the reference caption images and compare their hashes (RE-047).

The baseline (``data/regression/reference_builds.json``) lists each confirmed
build: its spec and spec hash, and the hashes of its built track 01 and patched
files. For each reference the script:

1. checks the spec. With ``--driver``, a reference that has ``generate``
   arguments is regenerated by ``official_captions.py`` from the local arcade ROM
   first, so the generator is checked too. Otherwise the cached local spec is
   used. Either way, the spec hash must match the baseline;
2. rebuilds it with ``caption_compiler.py`` from the untouched source image
   (``--out-root``, an ignored path);
3. compares the track 01 and file hashes, and requires every compiler check to be
   true.

A reference whose inputs are absent (a spec under ``local/``, the source image)
is reported as skipped, not failed. ``--write-baseline`` records the observed
hashes of passing references as the new baseline; use it only when a change is
intended and explained. ``--report`` writes the Markdown regression report.
"""

from __future__ import annotations

import argparse
import contextlib
import datetime
import hashlib
import io
import json
from collections.abc import Iterator, Sequence
from pathlib import Path

from tools.text import caption_compiler, official_captions

BASELINE = Path("data/regression/reference_builds.json")
SOURCE_DIR = Path("local/disc_images/mshvsf_saturn_jp")
TRACK01 = "Marvel Super Heroes vs. Street Fighter (Japan) (Track 01).bin"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def booleans(node: object, path: str = "") -> Iterator[tuple[str, bool]]:
    """Every boolean leaf of a compiler manifest's ``checks``, with its path."""
    if isinstance(node, dict):
        for key, value in node.items():
            yield from booleans(value, f"{path}.{key}" if path else key)
    elif isinstance(node, list):
        for i, value in enumerate(node):
            yield from booleans(value, f"{path}[{i}]")
    elif isinstance(node, bool):
        yield path, node


def observed(manifest: dict[str, object]) -> dict[str, object]:
    """The hashes the baseline records, taken from a compiler manifest."""
    image, outputs = manifest["image"], manifest["outputs"]
    assert isinstance(image, dict) and isinstance(outputs, dict)
    return {
        "spec_sha256": manifest["spec_sha256"],
        "track01_sha256": image["output_sha256"][TRACK01],
        "files_sha256": dict(sorted(outputs.items())),
    }


def compare(reference: dict[str, object], manifest: dict[str, object]) -> list[str]:
    """Mismatches between a baseline reference and a fresh compiler manifest."""
    problems = [
        f"check false: {path}"
        for section in ("checks", "image")
        for path, ok in booleans(manifest.get(section, {}))
        if not ok
    ]
    seen = observed(manifest)
    for key in ("spec_sha256", "track01_sha256"):
        if key in reference and reference[key] != seen[key]:
            problems.append(f"{key}: expected {reference[key]}, got {seen[key]}")
    expected_files = reference.get("files_sha256")
    if isinstance(expected_files, dict) and expected_files != seen["files_sha256"]:
        files = seen["files_sha256"]
        assert isinstance(files, dict)
        for name in sorted(set(expected_files) | set(files)):
            if expected_files.get(name) != files.get(name):
                problems.append(
                    f"file {name}: expected {expected_files.get(name)}, "
                    f"got {files.get(name)}"
                )
    if "track01_sha256" not in reference:
        problems.append("no baseline yet")
    return problems


def check_reference(
    reference: dict[str, object],
    baseline: dict[str, object],
    out_root: Path,
    source_dir: Path,
    driver: Path | None,
) -> dict[str, object]:
    name = str(reference["name"])
    out = out_root / name
    spec = Path(str(reference["spec"]))
    result: dict[str, object] = {"name": name, "spec_source": "cached"}
    generate = reference.get("generate")
    generator = baseline["generator"]
    assert isinstance(generator, dict)
    archive = Path(str(generator["archive"]))
    if driver is not None and isinstance(generate, list) and archive.exists():
        if sha256(driver) != generator["driver_sha256"]:
            return result | {"status": "fail", "problems": ["driver hash differs"]}
        out.mkdir(parents=True, exist_ok=True)
        spec = out / "spec.json"
        with contextlib.redirect_stdout(io.StringIO()):
            official_captions.main(
                ["--driver", str(driver), "--archive", str(archive), "--out", str(spec)]
                + [str(a) for a in generate]
            )
        result["spec_source"] = "regenerated"
    missing = [p for p in (spec, source_dir / TRACK01) if not p.exists()]
    if missing:
        return result | {
            "status": "skipped",
            "problems": [f"absent: {p}" for p in missing],
        }
    if sha256(spec) != reference["spec_sha256"]:
        return result | {
            "status": "fail",
            "problems": [
                f"spec_sha256: expected {reference['spec_sha256']}, got {sha256(spec)}"
            ],
        }
    with contextlib.redirect_stdout(io.StringIO()):
        code = caption_compiler.main(
            [
                str(spec),
                "--source-dir",
                str(source_dir),
                "--candidates",
                str(baseline["candidates"]),
                "--out-dir",
                str(out / "build"),
            ]
        )
    if code != 0:
        return result | {"status": "fail", "problems": [f"compiler exit {code}"]}
    manifest = json.loads((out / "build" / "compile_manifest.json").read_text())
    # The manifest names the spec path it was given; the hash is what matters.
    manifest["spec_sha256"] = sha256(spec)
    problems = compare(reference, manifest)
    return result | {
        "status": "pass" if not problems else "fail",
        "problems": problems,
        "observed": observed(manifest),
    }


def rebaseline(
    baseline: dict[str, object],
    results: Sequence[dict[str, object]],
    date: str,
    reason: str,
) -> list[str]:
    """Record observed hashes for references whose only problems are hash changes.

    A reference with a false compiler check, a changed spec, or a skip is left
    alone. A replaced track 01 hash moves to ``previous`` with ``reason``. Returns
    the names that were updated.
    """
    references = baseline["references"]
    assert isinstance(references, list)
    by_name = {str(r["name"]): r for r in references}
    updated = []
    for result in results:
        problems = result.get("problems", [])
        assert isinstance(problems, list)
        blocking = [
            p
            for p in problems
            if not str(p).startswith(("track01_sha256", "file ", "no baseline"))
        ]
        if result["status"] == "skipped" or blocking or "observed" not in result:
            continue
        seen = result["observed"]
        assert isinstance(seen, dict)
        reference = by_name[str(result["name"])]
        old = reference.get("track01_sha256")
        if old is not None and old != seen["track01_sha256"]:
            previous = reference.setdefault("previous", [])
            assert isinstance(previous, list)
            previous.append({"track01_sha256": old, "replaced_because": reason})
        reference["track01_sha256"] = seen["track01_sha256"]
        reference["files_sha256"] = seen["files_sha256"]
        reference["baselined"] = date
        updated.append(str(result["name"]))
    return updated


def report_markdown(
    baseline: dict[str, object], results: Sequence[dict[str, object]], date: str
) -> str:
    by_name = {str(r["name"]): r for r in results}
    references = baseline["references"]
    assert isinstance(references, list)
    lines = [
        "# Regression Report",
        "",
        "Generated by `tools/regression/reference_builds.py` (`RE-047`) from",
        "`data/regression/reference_builds.json`. Do not edit by hand; rerun:",
        "",
        "```bash",
        "./invenv.sh python -m tools.regression.reference_builds \\",
        "  --report docs/regression_report.md",
        "```",
        "",
        f"Last run: {date}.",
        "",
        "| Reference | Experiment | Spec SHA-256 | Track 01 SHA-256 | Baselined "
        "| Last check | Result |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for reference in references:
        name = str(reference["name"])
        result = by_name.get(name, {})
        status = str(result.get("status", "not run"))
        source = result.get("spec_source")
        if status == "pass" and source:
            status = f"pass ({source} spec)"
        spec = str(reference["spec_sha256"])[:16]
        track = str(reference.get("track01_sha256", "—"))[:16]
        baselined = reference.get("baselined", "—")
        checked = date if result else "—"
        lines.append(
            f"| `{name}` | `{reference['experiment']}` | `{spec}…` | `{track}…` "
            f"| {baselined} | {checked} | {status} |"
        )
    lines += ["", "## Patched Files", ""]
    for reference in references:
        files = reference.get("files_sha256", {})
        assert isinstance(files, dict)
        lines += [f"### `{reference['name']}`", "", f"{reference['purpose']}", ""]
        lines += ["| File | SHA-256 |", "| --- | --- |"]
        lines += [f"| `{name}` | `{digest}` |" for name, digest in files.items()]
        lines += ["", f"Track 01: `{reference.get('track01_sha256', '—')}`", ""]
        previous_hashes = reference.get("previous", [])
        assert isinstance(previous_hashes, list)
        for previous in previous_hashes:
            lines.append(
                f"- Previous track 01 `{previous['track01_sha256']}`: "
                f"{previous['replaced_because']}."
            )
        problems = by_name.get(str(reference["name"]), {}).get("problems", [])
        assert isinstance(problems, list)
        for problem in problems:
            lines.append(f"- Last run: {problem}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--baseline", type=Path, default=BASELINE)
    parser.add_argument("--out-root", type=Path, default=Path("build/regression"))
    parser.add_argument("--source-dir", type=Path, default=SOURCE_DIR)
    parser.add_argument("--driver", type=Path, help="pinned MAME cps2.cpp")
    parser.add_argument("--only", nargs="+", help="reference names to run")
    parser.add_argument("--write-baseline", action="store_true")
    parser.add_argument("--reason", help="why the hashes change (--write-baseline)")
    parser.add_argument("--report", type=Path, help="write the Markdown report")
    parser.add_argument("--date", default=datetime.date.today().isoformat())
    args = parser.parse_args(argv)
    if args.write_baseline and not args.reason:
        parser.error("--write-baseline needs --reason")
    baseline = json.loads(args.baseline.read_text())
    candidates = Path(baseline["candidates"])
    if candidates.exists() and sha256(candidates) != baseline["candidates_sha256"]:
        print(json.dumps({"error": "candidate census hash differs"}))
        return 1
    results = [
        check_reference(r, baseline, args.out_root, args.source_dir, args.driver)
        for r in baseline["references"]
        if not args.only or r["name"] in args.only
    ]
    if args.write_baseline:
        updated = rebaseline(baseline, results, args.date, args.reason)
        args.baseline.write_text(
            json.dumps(baseline, indent=1, ensure_ascii=False) + "\n"
        )
        for result in results:
            if result["name"] in updated:
                result["status"], result["problems"] = "pass", []
        print(json.dumps({"rebaselined": updated}))
    if args.report:
        args.report.write_text(report_markdown(baseline, results, args.date))
    summary = [
        {k: r[k] for k in ("name", "status", "spec_source", "problems") if k in r}
        for r in results
    ]
    print(json.dumps(summary, indent=1))
    return 0 if all(r["status"] != "fail" for r in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
